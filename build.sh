#!/bin/sh
# build.sh - THE ONE ENGINE of the repo root views of the two tree folders.
#
#   A0_repos-tree/          src/ (inputs: repos-tree.html.tmpl, repos-tree.md.tmpl, kinds.json, gh-meta.json)
#                           dist/ (outputs: repos-tree.{json,html,md,xml,canvas} + the Obsidian notes folder repos-tree/)
#   A1_repos-tree-folders/  src/ (inputs: repo-folders-tree.html.tmpl, repo-folders-tree.md.tmpl)
#                           dist/ (outputs: repo-folders-tree.{json,html,md})
#
# Step 1  render  src -> dist: `node 0_registry/gen-registry.js --no-consumers` re-renders every generated file from the one
#         master 0_registry/projects-repos.json plus the src/ inputs (no rewrite, no network, no sibling-clone writes). The
#         folder data inside the master is refreshed separately and only on demand: `./build.sh --refresh` runs
#         `node 0_registry/refresh-folders-tree.js` first; `./build.sh --scan` runs `node 0_registry/scan-kinds.js` first
#         (re-derives the html/lfs/code kind and the GitHub metadata cache of every repo; both need `gh` and network).
# Step 2  deploy  dist -> root: the published outputs of each folder (.json .md .html .xml .canvas that exist in its dist/) are
#         COPIED (real files, never symlinks) to the repo root: repos-tree.* and repo-folders-tree.*. The .md and .html copies
#         carry a one-line "generated by build.sh" comment (after the YAML frontmatter in the .md, after the doctype in the
#         .html); the other copies are byte-copies (JSON, XML and canvas have no comment syntax we may add; see README.md).
#   A2_repo-readmes/        src/ (README.html.tmpl, style.css) -> dist/<repo>/README.{html,canvas} (rendered by the same run; deploy: deploy-readmes.sh)
# Idempotent: a second run changes nothing. Drift guard: 9_others/test/test-root-copies.sh.
#   ./build.sh            render + deploy          ./build.sh --refresh | --scan    refresh data first, then render + deploy
set -eu
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"

[ "${1:-}" = "--refresh" ] && node 0_registry/refresh-folders-tree.js
[ "${1:-}" = "--scan" ] && node 0_registry/scan-kinds.js
node 0_registry/gen-registry.js --no-consumers
# A2_repo-readmes: dist/<repo>/README.{html,canvas} for every repo (deployed to the child clones by A2_repo-readmes/deploy-readmes.sh, not here)
node 0_registry/render-repo-readmes.js

NOTE='generated by build.sh - edit the sources in A0_repos-tree/src or A1_repos-tree-folders/src (master: 0_registry/projects-repos.json), never this copy'

# stamp <src> <dst>: copy src to dst; .md/.html get the note, everything else is a byte copy
stamp() {
  src="$1"; dst="$2"; tmp="$dst.tmp.$$"
  case "$src" in
    *.md) awk -v n="<!-- $NOTE -->" '
        NR == 1 && $0 == "---" { fm = 1; print; next }
        fm && $0 == "---" { fm = 0; print; print n; done = 1; next }
        NR == 1 { print n; done = 1 }
        { print }' "$src" > "$tmp" ;;
    *.html) awk -v n="<!-- $NOTE -->" '{ print } NR == 1 { print n }' "$src" > "$tmp" ;;
    *) cp "$src" "$tmp" ;;
  esac
  if [ -f "$dst" ] && [ ! -L "$dst" ] && cmp -s "$tmp" "$dst"; then rm -f "$tmp"; else rm -f "$dst"; mv "$tmp" "$dst"; echo "deployed $dst"; fi
}

for pair in A0_repos-tree:repos-tree A1_repos-tree-folders:repo-folders-tree; do
  dir="${pair%%:*}"; base="${pair##*:}"
  for ext in json md html xml canvas; do [ -f "$dir/dist/$base.$ext" ] && stamp "$dir/dist/$base.$ext" "$ROOT/$base.$ext"; done
done
echo "build.sh: root copies up to date"
